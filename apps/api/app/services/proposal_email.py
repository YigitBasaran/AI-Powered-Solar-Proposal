def recipient_for(proposal: Proposal) -> str:
    """The address this proposal goes to, from its frozen snapshot.

    Read from the snapshot rather than from the live customer record, so a
    recipient the operator confirmed cannot be changed underneath them by an
    edit to the customer between confirming and sending.
    """
    snapshot = proposal.customer_snapshot_json or {}
    raw = snapshot.get("email")
    if not isinstance(raw, str) or not raw.strip():
        raise RecipientUnavailableError(
            "This proposal has no customer, so there is nobody to email it to. "
            "Assign a customer to the project and finalise a new revision."
        )
    try:
        return normalise_email(raw)
    except Exception as error:  # pragma: no cover - stored addresses are normalised
        raise RecipientUnavailableError(
            "The stored customer address is not usable as an email recipient."
        ) from error


def _display_name(proposal: Proposal) -> str:
    snapshot = proposal.customer_snapshot_json or {}
    name = snapshot.get("displayName")
    return name if isinstance(name, str) and name.strip() else "there"


def _money(value: Any) -> str:
    try:
        return f"{float(value):,.0f}"
    except (TypeError, ValueError):  # pragma: no cover - snapshot values are numeric
        return str(value)


def compose(proposal: Proposal, settings: Settings) -> EmailMessage:
    """Render the message. Deterministic, and it sends nothing.

    Called by the preview route as well as the send route, from the same code
    with the same inputs - so what the operator was shown is exactly what goes
    out, rather than a rendering that merely resembles it.
    """
    snapshot = proposal.proposal_data_json or {}
    layout = snapshot.get("layout", {})
    financial = snapshot.get("financial", {})

    context = {
        "customer_name": _display_name(proposal),
        "public_url": f"{settings.web_base_url.rstrip('/')}/proposal/{proposal.share_token}",
        "reference": proposal.reference or proposal.share_token[:8],
        "system_size_kwp": f"{float(proposal.feasible_system_size_kwp):g}",
        "panel_count": proposal.panel_count,
        "annual_production_kwh": f"{float(proposal.annual_production_kwh):,.0f}",
        "annual_savings_eur": _money(
            financial.get("annualSavingsEur", proposal.annual_savings_eur)
        ),
        "capex_eur": _money(financial.get("convertedCapex", {}).get("amount", 0)),
        "payback_years": (
            f"{float(proposal.payback_years):.1f}" if proposal.payback_years else None
        ),
        "capacity_warning": proposal.capacity_warning or layout.get("capacityWarning"),
        "sender_name": settings.email_from_name or "SolarVis",
    }

    env = environment()
    return EmailMessage(
        to=recipient_for(proposal),
        subject=f"Your solar proposal - {context['system_size_kwp']} kWp ({context['reference']})",
        text_body=env.get_template("email/proposal.txt.j2").render(**context),
        html_body=env.get_template("email/proposal.html.j2").render(**context),
        reply_to=settings.email_reply_to or None,
    )


def preview(proposal: Proposal, settings: Settings) -> dict[str, Any]:
    """Everything the operator needs to decide, and nothing that sends.

    The full recipient is included deliberately: this is the confirmation step,
    and confirming a send to a masked address is not confirming anything. The
    masked form travels alongside for every *other* surface - logs, activity
    metadata, the delivery list.

    A proposal with no customer returns a preview with `to: null` rather than
    an error. A preview describes what *would* happen, and "nothing, because
    there is nobody to send to" is one of the answers - refusing here would
    leave the caller with a failed request and no way to explain itself, which
    is exactly the dead end the UI is trying to avoid.
    """
    sender = build_sender(settings)
    ready, reason = sender.available()

    try:
        message: EmailMessage | None = compose(proposal, settings)
    except RecipientUnavailableError:
        message = None

    return {
        "to": message.to if message else None,
        "toMasked": mask_email(message.to) if message else None,
        "subject": message.subject if message else None,
        "textBody": message.text_body if message else None,
        "htmlBody": message.html_body if message else None,
        "publicUrl": f"{settings.web_base_url.rstrip('/')}/proposal/{proposal.share_token}",
        "revisionNumber": proposal.revision_number or 1,
        "reference": proposal.reference,
        "from": settings.email_from or None,
        "fromName": settings.email_from_name,
        "replyTo": settings.email_reply_to or None,
        "provider": sender.name,
        # False for console. The UI reads this to decide between "Send" and
        # "Record locally", so the operator is never told a message left the
        # building when it did not.
        "providerSends": sender.name != "console",
        "providerAvailable": ready,
        "providerDetail": reason,
        "includesPdf": settings.proposal_email_attach_pdf,
    }


