def idempotency_key(proposal: Proposal, recipient: str, *, nonce: str = "") -> str:
    """Deterministic, so every duplicate of one intent computes the same value.

    A double click, a browser refresh mid-send and a client-side retry all
    produce this key, and the UNIQUE index turns three requests into one row.
    A deliberate resend passes a nonce, because that *is* a different intent.
    """
    material = f"{proposal.id}:{recipient}:{proposal.revision_number or 1}:{nonce}"
    return hashlib.sha256(material.encode("utf-8")).hexdigest()[:32]


async def _find_by_key(session: AsyncSession, key: str) -> ProposalDelivery | None:
    return (
        await session.execute(
            select(ProposalDelivery).where(ProposalDelivery.idempotency_key == key)
        )
    ).scalar_one_or_none()


def _is_stale(delivery: ProposalDelivery, settings: Settings) -> bool:
    """Whether a `sending` row has been in flight implausibly long."""
    started = as_utc(delivery.last_attempt_at or delivery.requested_at)
    if started is None:  # pragma: no cover - both columns are always set
        return True
    window = timedelta(seconds=settings.smtp_timeout_seconds + STALE_SEND_MARGIN_SECONDS)
    return (as_utc(_utcnow()) or _utcnow()) - started > window


async def claim(
    session: AsyncSession,
    proposal: Proposal,
    *,
    recipient: str,
    provider: str,
    settings: Settings,
    nonce: str = "",
) -> ProposalDelivery:
    """Take ownership of one send, or refuse.

    Returns a row in `sending`. Raises rather than returning one that somebody
    else owns, so a caller that gets a row here is unambiguously the one that
    may call the provider.
    """
    key = idempotency_key(proposal, recipient, nonce=nonce)

    delivery = await _find_by_key(session, key)
    if delivery is None:
        candidate = ProposalDelivery(
            proposal_id=proposal.id,
            recipient=recipient,
            provider=provider,
            status=PENDING,
            idempotency_key=key,
        )
        try:
            async with session.begin_nested():
                session.add(candidate)
                await session.flush()
            delivery = candidate
        except IntegrityError:
            # Two requests arrived together. The index refused the second, which
            # is the whole point; the loser works with the winner's row.
            logger.info("delivery race on proposal %s; re-selecting the winner", proposal.id)
            delivery = await _find_by_key(session, key)
            if delivery is None:  # pragma: no cover - the constraint guarantees one
                raise

    if delivery.status == SENT:
        raise ProposalAlreadySentError(
            f"This proposal was already sent to {mask_email(delivery.recipient)} on "
            f"{iso_utc(delivery.sent_at)}.",
            details={"deliveryId": delivery.id, "sentAt": iso_utc(delivery.sent_at)},
        )

    takeable = [PENDING, FAILED]
    if delivery.status == SENDING and _is_stale(delivery, settings):
        # The owner is long gone - a process that died, or a request abandoned
        # mid-flight. Reclaimable, and the honest consequence is stated in the
        # docs: if that attempt did reach the relay, this produces a second
        # copy. At-least-once, not exactly-once.
        logger.warning("reclaiming a stale delivery %s for proposal %s", delivery.id, proposal.id)
        takeable.append(SENDING)

    # The conditional UPDATE *is* the lock. Reading the status and then writing
    # it would leave a window two requests can both pass through.
    result: CursorResult[Any] = await session.execute(  # type: ignore[assignment]
        update(ProposalDelivery)
        .where(
            ProposalDelivery.id == delivery.id,
            ProposalDelivery.status.in_(takeable),
        )
        .execution_options(synchronize_session=False)
        .values(
            status=SENDING,
            provider=provider,
            attempt_count=ProposalDelivery.attempt_count + 1,
            last_attempt_at=_utcnow(),
            last_error_code=None,
            last_error_message=None,
        )
    )
    if result.rowcount == 0:
        raise DeliveryInProgressError(
            "This proposal is already being sent. Wait a moment and check its status.",
            details={"deliveryId": delivery.id},
        )

    await session.refresh(delivery)
    return delivery


async def _finish(
    session: AsyncSession,
    delivery: ProposalDelivery,
    **values: Any,
) -> bool:
    """Write a terminal status, fenced on this attempt still owning the row."""
    result: CursorResult[Any] = await session.execute(  # type: ignore[assignment]
        update(ProposalDelivery)
        .where(ProposalDelivery.id == delivery.id, ProposalDelivery.status == SENDING)
        .execution_options(synchronize_session=False)
        .values(**values)
    )
    await session.refresh(delivery)
    return bool(result.rowcount)


async def send(
    session: AsyncSession,
    proposal: Proposal,
    *,
    settings: Settings,
    sender: ProposalEmailSender | None = None,
    nonce: str = "",
    commit: Any = None,
) -> ProposalDelivery:
    """Compose, claim, hand to the provider, record the outcome.

    `commit` is the caller's commit function, invoked *before* the provider
    call. That ordering is the whole reliability story: it makes the `sending`
    row durable, so a process that dies mid-send leaves evidence rather than
    silence.
    """
    if not settings.proposal_email_enabled:
        raise EmailProviderUnavailableError(
            "Proposal email is switched off. The proposal can still be shared by link."
        )

    sender = sender or build_sender(settings)
    ready, reason = sender.available()
    if not ready:
        # Refused before a row moves to `sending`, so a misconfiguration leaves
        # nothing half-claimed to clean up.
        raise EmailProviderUnavailableError(
            f"Email is not configured, so this proposal cannot be sent. {reason or ''}".strip()
        )

    recipient = recipient_for(proposal)
    message = compose(proposal, settings)

    delivery = await claim(
        session,
        proposal,
        recipient=recipient,
        provider=sender.name,
        settings=settings,
        nonce=nonce,
    )

    await activity.record(
        session,
        event_type=activity.PROPOSAL_SEND_REQUESTED,
        actor="user",
        project_id=proposal.project_id,
        proposal_id=proposal.id,
        delivery_id=delivery.id,
        metadata={
            "recipientMasked": mask_email(recipient),
            "revisionNumber": proposal.revision_number or 1,
        },
    )

    if commit is not None:
        await commit(session)

    try:
        result = await sender.send(message)
    except EmailSendError as error:
        await _finish(
            session,
            delivery,
            status=FAILED,
            failed_at=_utcnow(),
            last_error_code=error.code,
            last_error_message=error.detail[:500],
        )
        await activity.record_best_effort(
            session,
            event_type=activity.PROPOSAL_EMAIL_FAILED,
            project_id=proposal.project_id,
            proposal_id=proposal.id,
            delivery_id=delivery.id,
            metadata={
                "recipientMasked": mask_email(recipient),
                "provider": sender.name,
                "errorCode": error.code,
            },
        )
        if commit is not None:
            await commit(session)

        logger.warning(
            "delivery %s failed for %s: %s", delivery.id, mask_email(recipient), error.code
        )
        if error.code == "EMAIL_SEND_TIMEOUT":
            raise EmailSendTimeoutError(
                "The mail server did not respond in time, so it is not known whether the "
                "proposal was sent. Check the delivery status before retrying.",
                details={"deliveryId": delivery.id},
            ) from error
        if error.code == "EMAIL_PROVIDER_UNAVAILABLE":
            raise EmailProviderUnavailableError(error.detail) from error
        raise EmailSendFailedError(
            error.detail or "The proposal could not be emailed.",
            details={"deliveryId": delivery.id},
        ) from error

    await _finish(
        session,
        delivery,
        status=SENT,
        sent_at=result.accepted_at,
        provider=result.provider,
        provider_message_id=result.provider_message_id,
        last_error_code=None,
        last_error_message=None,
    )
    await activity.record_best_effort(
        session,
        event_type=activity.PROPOSAL_EMAIL_SENT,
        actor="user",
        project_id=proposal.project_id,
        proposal_id=proposal.id,
        delivery_id=delivery.id,
        metadata={
            "recipientMasked": mask_email(recipient),
            "provider": result.provider,
            "revisionNumber": proposal.revision_number or 1,
        },
    )

    logger.info(
        "delivery %s %s via %s to %s",
        delivery.id,
        "recorded" if not result.delivered_to_provider else "accepted",
        result.provider,
        mask_email(recipient),
    )
    return delivery


async def notify_opened(
    session: AsyncSession,
    proposal: Proposal,
    *,
    view_id: str,
    view_count: int,
    settings: Settings,
    sender: ProposalEmailSender | None = None,
) -> bool:
    """Tell the salesperson their proposal was opened. Best-effort, always.

    The brief's bonus asks for a console *or* email notification on open; this
    is both, through the same provider as everything else, so console mode
    prints it and SMTP mode sends it.

    Guarded by `proposal_views.notified`, a column that has existed and been
    written by nothing since the first migration. Setting it here is what makes
    the notification fire once per counted view rather than once per request -
    and the flag is per view row, so it cannot suppress a genuinely new opening.

    Every failure is swallowed. A notification is for the operator; the
    customer is *currently looking at the page*, and nothing about their view
    may depend on an outbound email succeeding.
    """
    recipient = settings.salesperson_email.strip()
    if not recipient:
        return False

    view = await session.get(ProposalView, view_id)
    if view is None or view.notified:
        return False

    try:
        sender = sender or build_sender(settings)
        ready, _ = sender.available()
        if not ready:
            return False

        name = _display_name(proposal)
        url = f"{settings.web_base_url.rstrip('/')}/proposal/{proposal.share_token}"
        await sender.send(
            EmailMessage(
                to=recipient,
                subject=f"Proposal opened - {proposal.reference or proposal.share_token[:8]}",
                # The shape the case brief prints for the console notification,
                # kept verbatim so the two modes say the same thing.
                text_body=(
                    f"[Proposal Viewed]\n"
                    f"  Proposal:   {proposal.reference or proposal.share_token[:12]}\n"
                    f"  Customer:   {name}\n"
                    f"  Opened at:  {iso_utc(_utcnow())}\n"
                    f"  View count: {view_count}\n"
                    f"  Link:       {url}\n\n"
                    f"This is a view of the proposal page, not an email open - there is no "
                    f"open tracking in this system.\n"
                ),
            )
        )
        view.notified = True
        await session.flush()
        return True
    except Exception:
        logger.exception("open notification failed for %s; continuing", proposal.share_token[:8])
        return False


async def history(session: AsyncSession, proposal: Proposal) -> list[ProposalDelivery]:
    rows = (
        await session.execute(
            select(ProposalDelivery)
            .where(ProposalDelivery.proposal_id == proposal.id)
            .order_by(ProposalDelivery.requested_at.desc(), ProposalDelivery.id.desc())
        )
    ).scalars()
    return list(rows)


def serialise(delivery: ProposalDelivery) -> dict[str, Any]:
    """The delivery as the operator sees it.

    The recipient is **masked**. The full address is shown once, at the
    confirmation step, where the operator is deciding; a status list does not
    need it, and every surface that carries it is another place it leaks from.
    """
    return {
        "deliveryId": delivery.id,
        "proposalId": delivery.proposal_id,
        "channel": delivery.channel,
        "recipientMasked": mask_email(delivery.recipient),
        "status": delivery.status,
        "provider": delivery.provider,
        # The single field that keeps console mode honest downstream.
        "providerSends": delivery.provider != "console",
        "attemptCount": delivery.attempt_count,
        "errorCode": delivery.last_error_code,
        "errorMessage": delivery.last_error_message,
        "requestedAt": iso_utc(delivery.requested_at),
        "lastAttemptAt": iso_utc(delivery.last_attempt_at),
        "sentAt": iso_utc(delivery.sent_at),
        "failedAt": iso_utc(delivery.failed_at),
    }


