logger = logging.getLogger("solarvis.proposal_email")

TEMPLATE_DIR = Path(__file__).resolve().parents[1] / "templates"

PENDING = "pending"
SENDING = "sending"
SENT = "sent"
FAILED = "failed"

#: How long a `sending` row is treated as genuinely in flight.
#:
#: Past this, a retry may take it. The window is the provider timeout plus room
#: for the surrounding work, so a request that is merely slow is never
#: overtaken by one that assumes it died.
STALE_SEND_MARGIN_SECONDS = 30.0

_environment: Environment | None = None


def environment() -> Environment:
    global _environment
    if _environment is None:
        _environment = Environment(
            loader=FileSystemLoader(str(TEMPLATE_DIR)),
            # On for both parts. A customer's display name is operator-entered
            # free text and reaches the HTML body unmodified.
            autoescape=select_autoescape(default=True, default_for_string=True),
            trim_blocks=True,
            lstrip_blocks=True,
        )
    return _environment


