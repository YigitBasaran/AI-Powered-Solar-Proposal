"""Emailing a proposal: compose, claim, send, record.

The composition half is deliberately dull. Every value comes from the frozen
snapshot, the prose around them is a fixed template, and **the language model
writes none of it**. It may write the executive summary *inside* the proposal,
where each number it produces is checked against the snapshot before it is
stored - but an email is sent once, cannot be corrected, and nobody re-reads it
against the figures. So it is generated by code.

The sending half is where the care is. There is no job queue in this
application, so the provider call happens inside the request; what makes that
safe is a database claim, borrowed wholesale from `services/analysis_claim.py`
because the shape of the problem is identical:

1. Insert the delivery row keyed on a deterministic idempotency key, letting
   the UNIQUE index settle any race - the loser re-selects the winner.
2. Take the row with a **conditional UPDATE** to `sending`. `rowcount == 0`
   means somebody else owns it, and no message is composed and no provider is
   called.
3. **Commit before the provider call.** So an ambiguous timeout leaves a
   durable `sending` row rather than nothing at all: the evidence that an
   attempt happened survives the process that made it.
4. Write the terminal status fenced on `status = 'sending'`.

What this buys is *at-least-once with a stable key*, and that is stated rather
than dressed up. A relay that accepts a message and then times out will be
retried, and the customer may receive two copies. Avoiding that needs a
transaction spanning the database and the mail server, which does not exist.
"""

